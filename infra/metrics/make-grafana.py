#!/usr/bin/env python3
"""Writes the Grafana alert rules and the SBC dashboard (Security plan items 10-11).
   python3 infra/metrics/make-grafana.py   → grafana/provisioning/alerting/rules.yml, grafana/dashboards/sbc.json
Edit the lists below, never the generated files."""
import json, os, yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DS = {'type': 'prometheus', 'uid': 'prometheus'}

# ------------------------------------------------------------------ alert rules
R = []
def rule(uid, title, expr, op, value, for_, summary, severity='warning'):
    R.append({
        'uid': uid, 'title': title, 'condition': 'B', 'for': for_,
        'noDataState': 'OK', 'execErrState': 'Error',
        'labels': {'severity': severity}, 'annotations': {'summary': summary},
        'data': [
            {'refId': 'A', 'relativeTimeRange': {'from': 900, 'to': 0}, 'datasourceUid': 'prometheus',
             'model': {'refId': 'A', 'expr': expr, 'instant': True, 'range': False, 'intervalMs': 30000, 'maxDataPoints': 43200}},
            {'refId': 'B', 'datasourceUid': '__expr__',
             'model': {'refId': 'B', 'type': 'threshold', 'expression': 'A', 'conditions': [{'evaluator': {'type': op, 'params': [value]}}]}},
        ],
    })

REQ = 'sbc_http_request_duration_seconds'
rule('sbc-service-down', 'Service injoignable', 'up{job="sbc"}', 'lt', 1, '3m',
     '{{ $labels.env }} {{ $labels.instance }} : Prometheus ne lit plus ses métriques depuis 3 min (service arrêté, nginx ou réseau).', 'critical')
rule('sbc-disk', 'Disque presque plein', '1 - sbc_host_disk_free_bytes / sbc_host_disk_total_bytes', 'gt', 0.85, '10m',
     'Serveur principal, {{ $labels.path }} : disque utilisé à {{ with $values.A }}{{ humanizePercentage .Value }}{{ end }} (seuil 85 %).', 'critical')
rule('sbc-memory', 'Mémoire presque pleine', '1 - sbc_host_memory_available_bytes / sbc_host_memory_total_bytes', 'gt', 0.90, '10m',
     'Serveur principal : mémoire utilisée à {{ with $values.A }}{{ humanizePercentage .Value }}{{ end }} (seuil 90 %).', 'critical')
rule('sbc-5xx', 'Erreurs serveur (5xx)',
     f'sum by (env, service) (rate({REQ}_count{{code="5xx"}}[10m])) / sum by (env, service) (rate({REQ}_count[10m]))'
     f' and on (env, service) sum by (env, service) (rate({REQ}_count[10m])) > 0.05',
     'gt', 0.02, '10m',
     '{{ $labels.env }} {{ $labels.service }} : {{ with $values.A }}{{ humanizePercentage .Value }}{{ end }} des requêtes finissent en erreur serveur depuis 10 min (seuil 2 %).')
rule('sbc-money-slow', 'Routes argent lentes',
     f'histogram_quantile(0.95, sum by (le, env, route) (rate({REQ}_bucket{{service="payment", route=~".*(withdraw|payout|transactions|payments/intents).*"}}[10m])))',
     'gt', 5, '10m',
     '{{ $labels.env }} payment {{ $labels.route }} : p95 de {{ with $values.A }}{{ humanizeDuration .Value }}{{ end }} depuis 10 min (seuil 5 s).')
rule('sbc-api-slow', 'API lente',
     f'histogram_quantile(0.95, sum by (le, env, service) (rate({REQ}_bucket{{route!="unmatched"}}[10m])))', 'gt', 2, '15m',
     '{{ $labels.env }} {{ $labels.service }} : p95 de {{ with $values.A }}{{ humanizeDuration .Value }}{{ end }} depuis 15 min (seuil 2 s).')
rule('sbc-mongo-down', 'MongoDB ne répond pas', 'sbc_mongo_up', 'lt', 1, '3m',
     '{{ $labels.env }} : MongoDB ne répond plus à user-service (serverStatus) depuis 3 min.', 'critical')
rule('sbc-mongo-cache', 'Cache MongoDB saturé',
     'sbc_mongo_cache_bytes{kind="used"} / ignoring(kind) sbc_mongo_cache_bytes{kind="max"}', 'gt', 0.95, '15m',
     '{{ $labels.env }} : cache WiredTiger rempli à {{ with $values.A }}{{ humanizePercentage .Value }}{{ end }} : les données de travail ne tiennent plus en mémoire.')
rule('sbc-event-loop', 'Service saturé (boucle d’événements)', 'sbc_nodejs_eventloop_lag_p99_seconds', 'gt', 0.5, '10m',
     '{{ $labels.env }} {{ $labels.service }} : la boucle Node prend {{ with $values.A }}{{ humanizeDuration .Value }}{{ end }} de retard (p99).')
rule('sbc-job-errors', 'Tâche planifiée en échec', 'sum by (env, service, task) (increase(sbc_job_runs_total{result="error"}[30m]))', 'gt', 2, '0s',
     '{{ $labels.env }} {{ $labels.service }} : la tâche {{ $labels.task }} a échoué {{ with $values.A }}{{ printf "%.0f" .Value }}{{ end }} fois en 30 min.')
rule('sbc-job-stale', 'Tâche de nuit non faite',
     'time() - sbc_job_last_success_timestamp_seconds{task=~"dormancy_nightly|ledger_check|finance_reconciliation|authenticator_adoption"}',
     'gt', 26 * 3600, '0s', '{{ $labels.env }} {{ $labels.service }} : {{ $labels.task }} n’a pas réussi depuis plus de 26 h.')

rules = {'apiVersion': 1, 'groups': [{'orgId': 1, 'name': 'sbc', 'folder': 'SBC', 'interval': '1m', 'rules': R}]}
with open(os.path.join(HERE, 'grafana/provisioning/alerting/rules.yml'), 'w') as f:
    f.write('# Generated by infra/metrics/make-grafana.py — edit there.\n')
    yaml.safe_dump(rules, f, sort_keys=False, allow_unicode=True, width=220)

# ------------------------------------------------------------------ dashboard
panels, y = [], 0
def panel(title, exprs, unit, w=12, h=8, kind='timeseries', legend='{{service}}', desc=''):
    global y
    x = 0 if not panels or panels[-1]['gridPos']['x'] + panels[-1]['gridPos']['w'] >= 24 else panels[-1]['gridPos']['x'] + panels[-1]['gridPos']['w']
    if x == 0 and panels:
        y = max(p['gridPos']['y'] + p['gridPos']['h'] for p in panels)
    p = {'id': len(panels) + 1, 'type': kind, 'title': title, 'description': desc, 'datasource': DS,
         'gridPos': {'x': x, 'y': y, 'w': w, 'h': h},
         'fieldConfig': {'defaults': {'unit': unit}, 'overrides': []},
         'targets': [{'refId': chr(65 + i), 'datasource': DS, 'expr': e, 'legendFormat': legend if isinstance(legend, str) else legend[i],
                      **({'instant': True, 'format': 'table'} if kind == 'table' else {})} for i, e in enumerate(exprs)]}
    if kind == 'table':
        p['options'] = {'sortBy': [{'displayName': 'Value', 'desc': True}]}
    panels.append(p)

E = 'env="$env"'
panel('Requêtes par seconde', [f'sum by (service) (rate({REQ}_count{{{E}}}[5m]))'], 'reqps')
panel('Part d’erreurs serveur (5xx)', [f'sum by (service) (rate({REQ}_count{{{E},code="5xx"}}[5m])) / sum by (service) (rate({REQ}_count{{{E}}}[5m]))'], 'percentunit')
panel('Temps de réponse p95', [f'histogram_quantile(0.95, sum by (le, service) (rate({REQ}_bucket{{{E},route!="unmatched"}}[5m])))'], 's')
panel('Temps de réponse p50 / p99 (tous services)',
      [f'histogram_quantile(0.5, sum by (le) (rate({REQ}_bucket{{{E},route!="unmatched"}}[5m])))',
       f'histogram_quantile(0.99, sum by (le) (rate({REQ}_bucket{{{E},route!="unmatched"}}[5m])))'], 's', legend=['p50', 'p99'])
panel('Routes les plus lentes (p95, 1 h)', [f'topk(15, histogram_quantile(0.95, sum by (le, service, route) (rate({REQ}_bucket{{{E},route!="unmatched"}}[1h]))))'],
      's', w=24, h=9, kind='table', legend='{{service}} {{route}}')
panel('Routes argent : p95', [f'histogram_quantile(0.95, sum by (le, route) (rate({REQ}_bucket{{{E},service="payment",route=~".*(withdraw|payout|transactions|payments/intents).*"}}[5m])))'],
      's', legend='{{route}}')
panel('Routes argent : erreurs 5xx / min', [f'sum by (route) (rate({REQ}_count{{{E},service="payment",code="5xx"}}[5m])) * 60'], 'short', legend='{{route}}')
panel('Durée des tâches planifiées', [f'sum by (task) (rate(sbc_job_duration_seconds_sum{{{E}}}[15m])) / sum by (task) (rate(sbc_job_duration_seconds_count{{{E}}}[15m]))'], 's', legend='{{task}}')
panel('Échecs des tâches (1 h)', [f'sum by (service, task) (increase(sbc_job_runs_total{{{E},result="error"}}[1h])) > 0'], 'short', kind='table', legend='{{service}} {{task}}')
panel('Disque utilisé (serveur principal)', [f'1 - sbc_host_disk_free_bytes{{{E}}} / sbc_host_disk_total_bytes{{{E}}}'], 'percentunit', w=8, legend='{{path}}')
panel('Mémoire utilisée (serveur principal)', [f'1 - sbc_host_memory_available_bytes{{{E}}} / sbc_host_memory_total_bytes{{{E}}}'], 'percentunit', w=8, legend='mémoire')
panel('Charge (load 1 min)', [f'sbc_host_load1{{{E}}}'], 'short', w=8, legend='load1')
panel('Cache MongoDB', [f'sbc_mongo_cache_bytes{{{E}}}'], 'bytes', w=8, legend='{{kind}}')
panel('Connexions MongoDB', [f'sbc_mongo_connections{{{E},state="current"}}'], 'short', w=8, legend='connexions')
panel('Retard de la boucle Node (p99)', [f'sbc_nodejs_eventloop_lag_p99_seconds{{{E}}}'], 's', w=8)
panel('Mémoire des services (RSS)', [f'sbc_process_resident_memory_bytes{{{E}}}'], 'bytes')
panel('Services joignables', [f'up{{job="sbc",{E}}}'], 'short', legend='{{instance}}')

dash = {
    'uid': 'sbc-overview', 'title': 'SBC : santé des services', 'tags': ['sbc'], 'timezone': 'Africa/Douala',
    'schemaVersion': 39, 'version': 1, 'refresh': '1m', 'time': {'from': 'now-6h', 'to': 'now'},
    'templating': {'list': [{'name': 'env', 'label': 'Environnement', 'type': 'query', 'datasource': DS,
                             'query': {'query': 'label_values(up{job="sbc"}, env)', 'refId': 'env'},
                             'current': {'text': 'preprod', 'value': 'preprod'}, 'refresh': 1}]},
    'panels': panels,
}
with open(os.path.join(HERE, 'grafana/dashboards/sbc.json'), 'w') as f:
    json.dump(dash, f, ensure_ascii=False, indent=1)
print(f'{len(R)} rules, {len(panels)} panels')
